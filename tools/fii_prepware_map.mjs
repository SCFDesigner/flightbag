#!/usr/bin/env node
// Link each FII test question (written-exams.html, course fii) to the closest scraped Prepware
// question (fii-study-2.html, course fii2) so the test can open "the Prepware explanation".
// Decrypts both banks in memory only (files stay locked) and writes ifr/fii-prepware.js —
// question IDs only, no question text. Re-run after rebuilding either bank:
//   EXAM_PASSWORD=… node tools/fii_prepware_map.mjs      (or let it read the Keychain like fii2_publish.sh)
// Score = 0.75 × stem word overlap + 0.25 × correct-answer overlap (Jaccard, words > 2 letters,
// "(Refer to figure …)" ignored). ≥ 0.6 = same question, 0.3–0.6 = similar question on the same concept.
import { readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { webcrypto as C } from 'node:crypto';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const unb64 = s => new Uint8Array(Buffer.from(s, 'base64'));
const pw = process.env.EXAM_PASSWORD || execSync('security find-generic-password -s flightbag-exam-vault -w', { encoding: 'utf8' }).trim();

async function bank(file) {
  const html = readFileSync(join(ROOT, file), 'utf8');
  const raw = html.match(/<script id="vault" type="application\/json"[^>]*>([\s\S]*?)<\/script>/)[1].trim();
  if (!raw) return JSON.parse(html.match(/<script id="data" type="application\/json">([\s\S]*?)<\/script>/)[1]);  // unlocked page
  const env = JSON.parse(raw);
  const base = await C.subtle.importKey('raw', new TextEncoder().encode(pw), 'PBKDF2', false, ['deriveKey']);
  const key = await C.subtle.deriveKey({ name: 'PBKDF2', salt: unb64(env.salt), iterations: env.iter, hash: 'SHA-256' },
    base, { name: 'AES-GCM', length: 256 }, false, ['decrypt']);
  const pt = await C.subtle.decrypt({ name: 'AES-GCM', iv: unb64(env.iv) }, key, unb64(env.ct));
  return JSON.parse(JSON.parse(new TextDecoder().decode(pt)).data);
}

const A = (await bank('written-exams.html')).courses.fii.questions;
const B = (await bank('fii-study-2.html')).courses.fii2.questions;
const words = s => (s || '').toLowerCase().replace(/\(refer to [^)]*\)/g, ' ').replace(/[^a-z0-9 ]+/g, ' ').split(/\s+/).filter(w => w.length > 2);
const answer = q => q.choices.filter(c => c.c).map(c => c.t).join(' ');
const jac = (a, b) => { const x = new Set(a), y = new Set(b); let i = 0; x.forEach(w => { if (y.has(w)) i++; }); return i / (x.size + y.size - i || 1); };
const bt = B.map(q => ({ id: q.id, s: words(q.stem), a: words(answer(q)) }));

const map = {};
for (const q of A) {
  const s = words(q.stem), a = words(answer(q));
  let best = null, bs = 0;
  for (const b of bt) { const sc = 0.75 * jac(s, b.s) + 0.25 * jac(a, b.a); if (sc > bs) { bs = sc; best = b; } }
  if (bs >= 0.3) map[q.id] = [best.id, bs >= 0.6 ? 1 : 0];
}
const same = Object.values(map).filter(v => v[1]).length;
writeFileSync(join(ROOT, 'ifr/fii-prepware.js'),
  `/* Generated by tools/fii_prepware_map.mjs — FII test question id → [Prepware (fii2) question id, 1 = same question / 0 = similar]. */\n` +
  `window.FII_PREPWARE = ${JSON.stringify(map)};\n`);
console.log(`ifr/fii-prepware.js: ${Object.keys(map).length} of ${A.length} FII questions linked (${same} same, ${Object.keys(map).length - same} similar)`);
